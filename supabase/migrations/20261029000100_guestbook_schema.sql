-- Guestbook foundation (Stage A): tables, constraints, indexes, and lockdown.
--
-- Browsers never touch these tables. Edge Functions call the SECURITY DEFINER
-- functions defined in later migrations, and those functions are the only
-- write path. Every table has RLS enabled with no policies, and all table
-- privileges are revoked explicitly so the result does not depend on the
-- project's "auto-expose new tables" setting.

create schema if not exists private;
comment on schema private is
  'Credentials, rate-limit state, and internal helpers. Never exposed through the Data API.';

revoke all on schema private from public, anon, authenticated, service_role;

-- One row per browser-tab session (a "visitor").
create table public.visitor_sessions (
  id uuid primary key default gen_random_uuid(),
  -- Identity (sequence) values are concurrency-safe; gaps after rollbacks are expected.
  visitor_number bigint generated always as identity unique,
  alias text not null check (char_length(alias) between 1 and 40),
  started_at timestamptz not null default now(),
  last_active_at timestamptz not null default now(),
  knock_count integer not null default 0 check (knock_count >= 0)
);

comment on table public.visitor_sessions is
  'Anonymous visitor sessions. Written only by SECURITY DEFINER API functions.';
comment on column public.visitor_sessions.visitor_number is
  'Public, sequential visitor number assigned at registration.';
comment on column public.visitor_sessions.knock_count is
  'Acknowledged cumulative door knocks for this session.';

-- Session credentials live outside the exposed schema. Only hashes are stored.
create table private.session_credentials (
  session_id uuid primary key references public.visitor_sessions (id) on delete cascade,
  -- SHA-256 of the raw 32-byte session token.
  token_hash bytea not null unique check (octet_length(token_hash) = 32),
  -- SHA-256 of the raw 32-byte registration key; cleared once the token is first used
  -- or the replay window ends.
  registration_hash bytea unique check (octet_length(registration_hash) = 32),
  -- Server-random salt used to derive the token from the registration key; cleared
  -- together with registration_hash so the token can no longer be re-derived.
  token_salt bytea check (octet_length(token_salt) = 32),
  created_at timestamptz not null default now(),
  constraint session_credentials_registration_pair
    check ((registration_hash is null) = (token_salt is null))
);

comment on table private.session_credentials is
  'Hashed session credentials. Raw tokens and registration keys are never stored.';

-- One row per revealed prize. The id is generated by the client so retries are idempotent.
create table public.prize_awards (
  id uuid primary key,
  session_id uuid not null references public.visitor_sessions (id) on delete restrict,
  prize_id text not null
    check (char_length(prize_id) <= 64 and prize_id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  object_name text not null check (char_length(object_name) between 1 and 80),
  adjective text not null check (char_length(adjective) between 1 and 40),
  location text not null check (char_length(location) between 1 and 80),
  awarded_at timestamptz not null default now()
);

comment on table public.prize_awards is
  'Gifts given. Duplicate prizes are allowed; each reveal has its own award id.';

create index prize_awards_session_id_idx on public.prize_awards (session_id);
-- Newest-first keyset pagination with a stable tiebreaker.
create index prize_awards_recent_idx on public.prize_awards (awarded_at desc, id desc);

-- Single-row aggregate maintained by triggers (next migration).
create table public.site_stats (
  id smallint primary key default 1 check (id = 1),
  visitor_count bigint not null default 0 check (visitor_count >= 0),
  gifts_given bigint not null default 0 check (gifts_given >= 0),
  door_knocks bigint not null default 0 check (door_knocks >= 0),
  updated_at timestamptz not null default now()
);

comment on table public.site_stats is
  'Totals: visitors, gifts given, door knocks. Maintained transactionally by triggers.';

insert into public.site_stats (id) values (1);

-- Fixed-window rate-limit counters, one row per policy and subject.
create table private.rate_limit_buckets (
  bucket_key text primary key check (char_length(bucket_key) <= 200),
  window_started_at timestamptz not null,
  used integer not null check (used >= 0)
);

alter table public.visitor_sessions enable row level security;
alter table public.prize_awards enable row level security;
alter table public.site_stats enable row level security;
alter table private.session_credentials enable row level security;
alter table private.rate_limit_buckets enable row level security;

revoke all on table
  public.visitor_sessions,
  public.prize_awards,
  public.site_stats,
  private.session_credentials,
  private.rate_limit_buckets
from public, anon, authenticated, service_role;

revoke all on sequence public.visitor_sessions_visitor_number_seq
  from public, anon, authenticated, service_role;
