/**
 * Generates supabase/functions/_shared/prizeCatalog.generated.ts from src/data/prizes.ts, so the
 * Edge Functions validate awards against the same catalog the browser picks prizes from.
 *
 *   node --experimental-strip-types scripts/generate-prize-catalog.ts           write the file
 *   node --experimental-strip-types scripts/generate-prize-catalog.ts --check   fail if it is stale
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PRIZES, type PrizeDefinition } from '../src/data/prizes.ts'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = join(ROOT, 'supabase/functions/_shared/prizeCatalog.generated.ts')

// Must stay within the CHECK constraints on public.prize_awards.
const PRIZE_ID_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/
const MAX_PRIZE_ID = 64
const MAX_OBJECT_NAME = 80
const MAX_ADJECTIVE = 40
const MAX_LOCATION = 80

interface CatalogEntry {
  id: string
  objectName: string
  adjectives: string[]
  locations: string[]
}

function fail(message: string): never {
  throw new Error(`Prize catalog: ${message}`)
}

function checkText(value: string, max: number, label: string): void {
  const length = [...value].length
  if (length < 1 || length > max) {
    fail(`${label} must be 1-${max} characters: ${JSON.stringify(value)}`)
  }
  if (value.trim() !== value) {
    fail(`${label} has leading or trailing whitespace: ${JSON.stringify(value)}`)
  }
  if (/\p{Cc}/u.test(value)) {
    fail(`${label} contains a control character: ${JSON.stringify(value)}`)
  }
}

function buildCatalog(prizes: readonly PrizeDefinition[]): CatalogEntry[] {
  if (prizes.length === 0) fail('src/data/prizes.ts has no prizes')
  const seen = new Set<string>()
  return prizes.map((prize) => {
    const { id } = prize
    if (id.length > MAX_PRIZE_ID || !PRIZE_ID_PATTERN.test(id)) {
      fail(`invalid prize id ${JSON.stringify(id)}`)
    }
    if (seen.has(id)) fail(`duplicate prize id ${JSON.stringify(id)}`)
    seen.add(id)

    if (prize.image !== `/media/prizes/${id}.webp`) {
      fail(`${id} image path must be /media/prizes/${id}.webp`)
    }
    if (!existsSync(join(ROOT, 'public', prize.image))) {
      fail(`${id} image is missing: public${prize.image}`)
    }

    checkText(prize.name, MAX_OBJECT_NAME, `${id} name`)
    const adjectives = [...new Set(prize.adjectives)]
    const locations = [...new Set(prize.locations)]
    if (adjectives.length === 0) fail(`${id} has no adjectives`)
    if (locations.length === 0) fail(`${id} has no locations`)
    for (const adjective of adjectives) checkText(adjective, MAX_ADJECTIVE, `${id} adjective`)
    for (const location of locations) checkText(location, MAX_LOCATION, `${id} location`)

    return { id, objectName: prize.name, adjectives, locations }
  })
}

function renderCatalog(entries: readonly CatalogEntry[]): string {
  const literal = (value: string) => JSON.stringify(value)
  const lines = [
    '// Generated by scripts/generate-prize-catalog.ts from src/data/prizes.ts. Do not edit.',
    '// After changing src/data/prizes.ts, run `npm run catalog:generate`.',
    '',
    'export interface CatalogPrize {',
    '  readonly id: string',
    '  readonly objectName: string',
    '  readonly adjectives: readonly string[]',
    '  readonly locations: readonly string[]',
    '}',
    '',
    'export const PRIZE_CATALOG: readonly CatalogPrize[] = [',
  ]
  for (const entry of entries) {
    lines.push(
      '  {',
      `    id: ${literal(entry.id)},`,
      `    objectName: ${literal(entry.objectName)},`,
      `    adjectives: [${entry.adjectives.map(literal).join(', ')}],`,
      `    locations: [${entry.locations.map(literal).join(', ')}],`,
      '  },',
    )
  }
  lines.push(']', '')
  return lines.join('\n')
}

const entries = buildCatalog(PRIZES)
const source = renderCatalog(entries)
const outputPath = relative(ROOT, OUTPUT)

if (process.argv.includes('--check')) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : ''
  if (current !== source) {
    console.error(`${outputPath} is out of date. Run: npm run catalog:generate`)
    process.exit(1)
  }
  console.log(`${outputPath} is up to date (${entries.length} prizes).`)
} else {
  writeFileSync(OUTPUT, source)
  console.log(`Wrote ${entries.length} prizes to ${outputPath}.`)
}
